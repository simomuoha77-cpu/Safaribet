const fs=require('fs'); const vm=require('vm');
const s=fs.readFileSync(require('path').join(__dirname,'../../public/index.html'),'utf8');
const a=s.indexOf('function estimateMinute'), b=s.indexOf('function startLiveTimer');
const ctx={Date, Math, String, Number, Number, Date}; vm.createContext(ctx); vm.runInContext(s.slice(a,b),ctx);
const f=ctx.formatLiveMinuteDisplay; let ok=0,bad=0;
const t=(n,got,want)=>{ (got===want?ok++:bad++); console.log((got===want?'PASS ':'FAIL ')+n+' -> '+got+(got===want?'':' (wanted '+want+')')); };
const ko=new Date(Date.now()-140*60000).toISOString();
t('minute 67 real',            f(67,'2H',false,ko,'football'), '2H 67');
t('minute 90 real',            f(90,'2H',false,ko,'football'), '2H 90');
